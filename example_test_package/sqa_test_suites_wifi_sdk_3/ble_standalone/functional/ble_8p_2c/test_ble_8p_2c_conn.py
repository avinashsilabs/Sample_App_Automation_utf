def test_3s_1m_connection_on_dut(ble_dut, remote_wiseconnect3,remote_wiseconnect3s):
        ble_dut.interfaces.bluetooth.ble_unified_app_start()
        bt_dut_address = ble_dut.interfaces.wifi.bt_get_local_address()
        remote_wiseconnect3.interfaces.wifi.ble_unified_app_start()
        remote_wiseconnect3s[0].interfaces.wifi.ble_unified_app_start()
        remote_wiseconnect3s[1].interfaces.wifi.ble_unified_app_start()
        remote_wiseconnect3s[2].interfaces.wifi.ble_unified_app_start()
        logger().info("=====connection to remote-1")
        ble_client_address = remote_wiseconnect3.interfaces.wifi.bt_get_local_address()
        remote_wiseconnect3.interfaces.wifi.ble_start_advertising()
        ble_dut.interfaces.bluetooth.ble_start_scanning(ble_client_address=ble_client_address)
        time.sleep(3)
        ble_dut.interfaces.bluetooth.ble_stop_scanning()
        time.sleep(1)
        ble_dut.interfaces.bluetooth.ble_connect(ble_remote_dev_address=ble_client_address)
        time.sleep(10)
        ble_dut.interfaces.bluetooth.ble_get_device_state()
        time.sleep(1)
        logger().info("=====connection to remote-2")
        remote_wiseconnect3s[0].interfaces.wifi.ble_start_advertising()
        ble_client_address_1 = remote_wiseconnect3s[0].interfaces.wifi.bt_get_local_address()
        ble_dut.interfaces.bluetooth.ble_start_scanning(ble_client_address=ble_client_address_1)
        time.sleep(3)
        ble_dut.interfaces.bluetooth.ble_stop_scanning()
        time.sleep(1)
        ble_dut.interfaces.bluetooth.ble_connect(ble_remote_dev_address=ble_client_address_1)
        time.sleep(10)
        ble_dut.interfaces.bluetooth.ble_get_device_state()
        logger().info("=====connection to remote-3")
        remote_wiseconnect3s[1].interfaces.wifi.ble_start_advertising()
        ble_client_address_2 = remote_wiseconnect3s[1].interfaces.wifi.bt_get_local_address()
        ble_dut.interfaces.bluetooth.ble_start_scanning(ble_client_address=ble_client_address_2)
        time.sleep(3)
        ble_dut.interfaces.bluetooth.ble_stop_scanning()
        time.sleep(1)
        ble_dut.interfaces.bluetooth.ble_connect(ble_remote_dev_address=ble_client_address_2)
        time.sleep(10)
        ble_dut.interfaces.bluetooth.ble_get_device_state()
        logger().info("=====connection to remote-4")
        remote_wiseconnect3s[2].interfaces.wifi.ble_start_advertising()
        ble_client_address_3 = remote_wiseconnect3s[2].interfaces.wifi.bt_get_local_address()
        time.sleep(1)
        ble_dut.interfaces.bluetooth.ble_start_scanning(ble_client_address=ble_client_address_3)
        time.sleep(1)
        ble_dut.interfaces.bluetooth.ble_stop_scanning()
        time.sleep(1)
        ble_dut.interfaces.bluetooth.ble_connect(ble_remote_dev_address=ble_client_address_3)
        time.sleep(1)
        ble_dut.interfaces.bluetooth.ble_get_device_state()
        time.sleep(60)
        logger().info("state after 60 secs")
        ble_dut.interfaces.bluetooth.ble_get_device_state()
        time.sleep(1)
        ble_dut.interfaces.bluetooth.ble_disconnect(ble_remote_dev_address=ble_client_address)
        time.sleep(1)
        ble_dut.interfaces.bluetooth.ble_disconnect(ble_remote_dev_address=ble_client_address_1)
        time.sleep(1)
        ble_dut.interfaces.bluetooth.ble_disconnect(ble_remote_dev_address=ble_client_address_2)
        time.sleep(1)
        ble_dut.interfaces.bluetooth.ble_disconnect(ble_remote_dev_address=ble_client_address_3)



